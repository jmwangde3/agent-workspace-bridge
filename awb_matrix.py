# -*- coding: utf-8 -*-
"""技能 × 工作空间 矩阵：图形界面的直接事实源，也是各 CLI 的统一解析层。

优先级：
  1. skills-matrix.json 存在且结构合法 → 以它的 global + workspaces 为准。
     skills-workspaces.json 里的 rules / bundles 完全不参与，界面上的勾选就是事实。
  2. 该文件不存在 → 把 skills-workspaces.json 的 rules 展开成同样的结构。
     这是旧 CLI 的行为，保证没有界面时一切照旧。

矩阵文件由 awb_gui.py 写入，CLI 脚本只读。结构：
    {
      "note": "...",
      "source": "matrix" | "rules",
      "global": ["skill-a", ...],
      "workspaces": { "WS-NAME": ["skill-x", ...], "...": [] }
    }
"""
import os
import re
import json

from awb_config import CFG, MATRIX, WORKSPACE_ROOT, VAULT

NOTE = ("GENERATED by awb_gui.py — 图形界面的勾选结果。"
        "global = 所有工作空间可见；workspaces = 每个工作空间专属技能。"
        "删除本文件即回到 skills-workspaces.json 的 rules 模式。")


def load_rules():
    with open(CFG, encoding="utf-8") as f:
        return json.load(f)


def vault_names():
    """保管库里的技能名（技能真实目录的链接全集）。"""
    if not os.path.isdir(VAULT):
        return []
    return sorted(n for n in os.listdir(VAULT) if not n.startswith("."))


def list_workspaces():
    """工作空间根目录下所有子目录名。"""
    if not os.path.isdir(WORKSPACE_ROOT):
        return []
    return sorted(n for n in os.listdir(WORKSPACE_ROOT)
                  if os.path.isdir(os.path.join(WORKSPACE_ROOT, n)) and not n.startswith("."))


def _rules_global(cfg):
    pool = set(vault_names())
    return [n for n in cfg.get("global", []) if n in pool]


def _rules_for(name, cfg):
    """第一条命中的规则生效；返回 (技能名列表, 命中的正则)。"""
    for r in cfg.get("rules", []):
        if re.search(r["match"], name):
            out = []
            for b in r.get("bundles", []):
                out.extend(cfg.get("bundles", {}).get(b, []))
            return out, r["match"]
    return [], None


def from_rules(cfg=None, workspaces=None):
    """把规则表展开成矩阵结构（首次打开界面、或矩阵文件缺失时用）。"""
    cfg = cfg or load_rules()
    ws = list_workspaces() if workspaces is None else workspaces
    pool = set(vault_names())
    data = {"note": NOTE, "source": "rules", "global": _rules_global(cfg), "workspaces": {}}
    for name in ws:
        names, _ = _rules_for(name, cfg)
        data["workspaces"][name] = [n for n in dict.fromkeys(names) if n in pool]
    return data


def load_matrix():
    """返回 (matrix dict, source)。坏文件自动回退，不抛异常。"""
    if os.path.isfile(MATRIX):
        try:
            with open(MATRIX, encoding="utf-8") as f:
                d = json.load(f)
            if isinstance(d.get("global"), list) and isinstance(d.get("workspaces"), dict):
                d.setdefault("note", NOTE)
                d["source"] = "matrix"
                return d, "matrix"
        except (OSError, ValueError):
            pass
    return from_rules(), "rules"


def save_matrix(data):
    """原子写入矩阵文件。"""
    data = dict(data)
    data["note"] = NOTE
    data["source"] = "matrix"
    os.makedirs(os.path.dirname(MATRIX), exist_ok=True)
    tmp = MATRIX + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    os.replace(tmp, MATRIX)
    return MATRIX


def global_skills(matrix=None):
    m = matrix if matrix is not None else load_matrix()[0]
    pool = set(vault_names())
    return [n for n in dict.fromkeys(m.get("global", [])) if n in pool]


def resolve(name, matrix=None):
    """某工作空间的专属技能列表。"""
    m = matrix if matrix is not None else load_matrix()[0]
    pool = set(vault_names())
    return [n for n in dict.fromkeys(m.get("workspaces", {}).get(name, [])) if n in pool]


def bundles_for(name, cfg=None):
    """兼容旧签名 (name, cfg) -> (技能名列表, 标签)。

    scope_skills.py / cross_agent_skills.py 都调这个；标签只用于日志显示。
    """
    m, source = load_matrix()
    if source == "matrix":
        return resolve(name, m), "matrix"
    cfg = cfg or load_rules()
    names, rule = _rules_for(name, cfg)
    pool = set(vault_names())
    return [n for n in dict.fromkeys(names) if n in pool], (rule or "-")


if __name__ == "__main__":
    m, src = load_matrix()
    print("source   :", src)
    print("file     :", MATRIX)
    print("workspaces:", len(m["workspaces"]))
    print("global   :", m["global"])
    for k, v in m["workspaces"].items():
        if v:
            print(" %-30s %s" % (k, v))
